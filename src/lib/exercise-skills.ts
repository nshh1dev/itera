export function exerciseSkillSummary(exercise: Pick<ExerciseCard, "slug" | "title" | "description" | "practiceGoals">) {
  const known = exercise.slug.startsWith("logica-") ? skills[exercise.slug.slice(7)] : undefined;
  if (known) return known;
  const normalize = (value: string) => value.trim().replace(/[.!]+$/, "").toLocaleLowerCase("es");
  const goals = [...new Set(exercise.practiceGoals?.map(goal => goal.trim()).filter(goal => goal && normalize(goal) !== normalize(exercise.title)))];
  return goals.slice(0, 2).join(" · ") || (normalize(exercise.description) !== normalize(exercise.title) ? exercise.description : "");
}
